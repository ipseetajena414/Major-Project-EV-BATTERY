"""
PADM Step 1 & 2: Delta Feature Construction and Chronological Splitting
=======================================================================

Produces a leak-free delta-target dataset from the NMC cycle-level feature
table generated by ``member2_modeling.build_and_train.build_cycle_feature_table``.

Key design decisions (see PADM_PRE_IMPLEMENTATION_REVIEW.md §1–2):

* delta_target = SOH(i+1) − SOH(i).  Positive values are physically valid
  (charge recovery, measurement noise) and are NOT suppressed.
* Lag features are built only from ground-truth SOH history (no predictions).
* Scalers are fit on training rows only; lags for the first rows per cell are
  imputed with the training-set mean *before* scaling.
* Feature columns are locked here; they must not be changed after test-set
  evaluation begins.
* SOH values are clipped to [0.0, 105.0] to accommodate NASA B0006's
  starting SOH of 101.77%.
"""

from __future__ import annotations

import json
import os
import warnings
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

warnings.filterwarnings("ignore", category=FutureWarning)

# ── Paths ─────────────────────────────────────────────────────────────────────
WORKSPACE = Path(__file__).resolve().parents[2]
PARQUET_PATH = WORKSPACE / "master_table.parquet"

ARTIFACT_DIR = (
    Path(__file__).resolve().parents[1] / "artifacts" / "delta"
)

CYCLE_KEY = ["dataset_id", "cell_id", "protocol_id", "cycle_id"]
TRAIN_FRAC, VAL_FRAC, TEST_FRAC = 0.60, 0.20, 0.20

# Physical upper bound: B0006 starts at 101.77%; allow 105 for rounding headroom
SOH_CLIP_MIN, SOH_CLIP_MAX = 0.0, 105.0

# Number of lag steps (depth-3 as per PADM review §1)
LAG_DEPTH = 3

# Locked feature set (≤20 columns; physically motivated; decided on val MAE)
# Selection rationale: these are the 12 features with the strongest physical
# link to electrochemical degradation across all three NASA NMC cells.
# Do NOT change this list after test-set evaluation.
PADM_FEATURE_COLS: list[str] = [
    # Electrochemical throughput
    "ah_throughput",
    "energy_wh",
    # Discharge voltage shape
    "v_mean",
    "v_std",
    "v_slope",
    "dvdt_mean",
    # Thermal indicators (NMC specific)
    "temp_mean",
    "temp_rise",
    # Cycle-level state
    "current_soh_pct",
    "cycle_position",
    # Lag SOH deltas (ground-truth based)
    "delta_lag_1",
    "delta_rolling_mean_3",
]

# All columns that must NOT appear in X (potential leakage or identifiers)
FORBIDDEN_IN_X: frozenset[str] = frozenset(
    [
        "target_soh_pct",
        "delta_target",
        "soh_pct",
        "capacity_ah",
        "target_cycle_id",
        "dataset_id",
        "cell_id",
        "protocol_id",
        "cycle_id",
        "chemistry",
        "split",
    ]
)


# ── Internal helpers ──────────────────────────────────────────────────────────


def _clip_soh(series: pd.Series) -> pd.Series:
    """Clip SOH to the physically valid [0, 105] window."""
    return series.clip(SOH_CLIP_MIN, SOH_CLIP_MAX)


def _build_delta_pairs_for_cell(cell_df: pd.DataFrame) -> pd.DataFrame:
    """
    Build one-step-ahead delta target pairs for a single cell.

    Parameters
    ----------
    cell_df : pd.DataFrame
        Cycle-level feature table for ONE cell, already sorted by cycle_id.
        Must contain ``soh_pct`` and ``current_soh_pct``.

    Returns
    -------
    pd.DataFrame with ``delta_target`` added and last row dropped
        (no future SOH available for the final cycle).
    """
    cell_df = cell_df.sort_values("cycle_id").reset_index(drop=True)
    cell_df["soh_pct"] = _clip_soh(cell_df["soh_pct"])

    n = len(cell_df)
    if n < 2:
        return pd.DataFrame()

    # Input rows: cycles 0 … n-2
    inputs = cell_df.iloc[: n - 1].copy().reset_index(drop=True)
    # Target: SOH of next observed record
    inputs["target_soh_pct"] = cell_df["soh_pct"].iloc[1:].values
    # current_soh_pct was already set by create_future_soh_dataset;
    # recompute from soh_pct to be safe
    inputs["current_soh_pct"] = cell_df["soh_pct"].iloc[: n - 1].values

    # Delta target: can be positive or negative
    inputs["delta_target"] = inputs["target_soh_pct"] - inputs["current_soh_pct"]

    return inputs


def _add_lag_features(cell_df: pd.DataFrame) -> pd.DataFrame:
    """
    Add lag delta features within a single cell's sorted rows.

    Lag features use the *ground-truth* SOH history, never model predictions.
    Missing values at the start of the series (boundary rows) are left as NaN
    here; they will be imputed with training-set mean before scaling.

    Features added
    --------------
    delta_lag_1        : delta_target at position i-1
    delta_lag_2        : delta_target at position i-2
    delta_rolling_mean_3 : rolling mean of delta_target over last 3 positions
                           (min_periods=1 so first row gets its own value)
    """
    cell_df = cell_df.copy()
    # Compute running delta from current_soh_pct sequence for rolling stats
    delta_series = cell_df["delta_target"]

    cell_df["delta_lag_1"] = delta_series.shift(1)
    cell_df["delta_lag_2"] = delta_series.shift(2)
    cell_df["delta_rolling_mean_3"] = (
        delta_series.shift(1).rolling(window=3, min_periods=1).mean()
    )
    return cell_df


# ── Public API ────────────────────────────────────────────────────────────────


def build_nmc_delta_pairs(
    cycle_feature_df: pd.DataFrame,
) -> pd.DataFrame:
    """
    Build the complete NMC delta-target dataset with lag features.

    Parameters
    ----------
    cycle_feature_df : pd.DataFrame
        Output of ``build_and_train.build_cycle_feature_table`` filtered to
        NMC chemistry only.  Must contain: ``cell_id``, ``cycle_id``,
        ``soh_pct``, ``cycle_position``, and all physics features.

    Returns
    -------
    pd.DataFrame
        One row per (cell, cycle) pair; columns include PADM_FEATURE_COLS
        (minus lags which are added here), ``delta_target``,
        ``current_soh_pct``, ``target_soh_pct``, ``split`` (added later by
        ``apply_chronological_splits``).

    Notes
    -----
    * Row count == Σ(cycles_per_cell − 1).  Verified downstream.
    * ``delta_target`` is NOT forced to be negative.
    """
    nmc_df = cycle_feature_df[cycle_feature_df["chemistry"] == "NMC"].copy()

    per_cell_frames: list[pd.DataFrame] = []
    for _cell_id, cell_data in nmc_df.groupby("cell_id"):
        pairs = _build_delta_pairs_for_cell(cell_data)
        if len(pairs) == 0:
            continue
        pairs = _add_lag_features(pairs)
        per_cell_frames.append(pairs)

    if not per_cell_frames:
        raise RuntimeError(
            "No NMC delta pairs could be constructed. "
            "Check that master_table.parquet contains NMC chemistry rows."
        )

    combined = pd.concat(per_cell_frames, ignore_index=True)
    return combined


def apply_chronological_splits(delta_df: pd.DataFrame) -> pd.DataFrame:
    """
    Apply per-cell 60/20/20 chronological splits to the delta-pair DataFrame.

    Splitting is applied per cell (not globally) to prevent future data from
    any cell leaking into earlier cells' training sets.

    Parameters
    ----------
    delta_df : pd.DataFrame
        Output of ``build_nmc_delta_pairs``.

    Returns
    -------
    pd.DataFrame with a ``split`` column ('train', 'val', 'test').
    """
    per_cell_frames: list[pd.DataFrame] = []
    for _cell_id, cell_data in delta_df.groupby("cell_id"):
        cell_data = cell_data.sort_values("cycle_id").reset_index(drop=True)
        n = len(cell_data)
        n_train = int(np.floor(n * TRAIN_FRAC))
        n_val = int(np.floor(n * VAL_FRAC))

        train = cell_data.iloc[:n_train].copy()
        val = cell_data.iloc[n_train : n_train + n_val].copy()
        test = cell_data.iloc[n_train + n_val :].copy()

        train["split"] = "train"
        val["split"] = "val"
        test["split"] = "test"

        per_cell_frames.append(pd.concat([train, val, test], ignore_index=True))

    if not per_cell_frames:
        raise RuntimeError("No cells found when applying chronological splits.")

    result = pd.concat(per_cell_frames, ignore_index=True)

    # Verify zero overlap between splits
    _verify_no_overlap(result)
    return result


def _verify_no_overlap(df: pd.DataFrame) -> None:
    """Assert that no (cell_id, cycle_id) pair appears in more than one split."""
    for cell_id, cell_data in df.groupby("cell_id"):
        pairs_per_split: dict[str, set] = {}
        for split, sdf in cell_data.groupby("split"):
            pairs_per_split[split] = set(sdf["cycle_id"].tolist())

        splits = list(pairs_per_split.keys())
        for i, s1 in enumerate(splits):
            for s2 in splits[i + 1 :]:
                overlap = pairs_per_split[s1] & pairs_per_split[s2]
                if overlap:
                    raise ValueError(
                        f"Cell {cell_id}: cycle_ids {overlap} appear in both "
                        f"'{s1}' and '{s2}' splits. Data leakage detected."
                    )


def impute_lag_nans_with_train_mean(
    df: pd.DataFrame,
    lag_cols: list[str] | None = None,
) -> tuple[pd.DataFrame, dict[str, float]]:
    """
    Impute NaN lag features using training-set mean (computed from training
    rows only).  Non-lag columns are NOT modified.

    Parameters
    ----------
    df : pd.DataFrame
        Full dataset with ``split`` column.
    lag_cols : list[str] or None
        Lag column names to impute.  Defaults to
        ['delta_lag_1', 'delta_lag_2', 'delta_rolling_mean_3'].

    Returns
    -------
    (imputed_df, impute_means)
        impute_means: dict mapping column name → training mean used.
    """
    if lag_cols is None:
        lag_cols = ["delta_lag_1", "delta_lag_2", "delta_rolling_mean_3"]

    train_mask = df["split"] == "train"
    impute_means: dict[str, float] = {}

    df = df.copy()
    for col in lag_cols:
        if col not in df.columns:
            continue
        train_mean = float(df.loc[train_mask, col].mean())
        impute_means[col] = train_mean
        df[col] = df[col].fillna(train_mean)

    return df, impute_means


def verify_feature_integrity(
    df: pd.DataFrame,
    feature_cols: list[str] | None = None,
) -> None:
    """
    Confirm that no forbidden column appears in the PADM feature set and that
    ``delta_target`` is not present in the feature matrix.

    Raises ``ValueError`` on any violation.
    """
    if feature_cols is None:
        feature_cols = PADM_FEATURE_COLS

    violations = [c for c in feature_cols if c in FORBIDDEN_IN_X]
    if violations:
        raise ValueError(
            f"Forbidden columns detected in PADM feature set: {violations}. "
            "This indicates data leakage. Remove them before proceeding."
        )

    if "delta_target" in feature_cols:
        raise ValueError(
            "delta_target (the label) is present in the feature list. "
            "Remove it immediately — this is data leakage."
        )


def build_and_save_delta_dataset(
    cycle_feature_df: pd.DataFrame,
    *,
    artifact_dir: Path | str | None = None,
) -> dict[str, Any]:
    """
    End-to-end function: build delta pairs → split → impute → save parquet.

    Parameters
    ----------
    cycle_feature_df : pd.DataFrame
        NMC cycle-level features from ``build_and_train.build_cycle_feature_table``.
    artifact_dir : Path or str, optional
        Override output directory.  Defaults to
        ``member2_modeling/artifacts/delta/``.

    Returns
    -------
    dict with keys:
        rows_per_split   : {'train': int, 'val': int, 'test': int}
        impute_means     : dict of lag imputation values
        output_path      : str path of saved parquet
        feature_cols     : list of locked feature columns
        integrity_passed : True
    """
    out_dir = Path(artifact_dir) if artifact_dir else ARTIFACT_DIR
    out_dir.mkdir(parents=True, exist_ok=True)

    # Step 1: build delta pairs per cell
    print("  [delta_features] Building NMC delta target pairs...")
    delta_df = build_nmc_delta_pairs(cycle_feature_df)
    print(f"  [delta_features] Total delta pairs: {len(delta_df)}")

    # Step 2: chronological split per cell
    print("  [delta_features] Applying chronological splits...")
    delta_df = apply_chronological_splits(delta_df)
    rows_per_split = {
        s: int((delta_df["split"] == s).sum())
        for s in ["train", "val", "test"]
    }
    print(f"  [delta_features] Split counts: {rows_per_split}")

    # Step 3: impute lag NaNs with training mean
    lag_cols = ["delta_lag_1", "delta_lag_2", "delta_rolling_mean_3"]
    delta_df, impute_means = impute_lag_nans_with_train_mean(delta_df, lag_cols)
    print(f"  [delta_features] Lag imputation means: {impute_means}")

    # Verify feature integrity (no leakage)
    verify_feature_integrity(delta_df, PADM_FEATURE_COLS)
    print("  [delta_features] Feature integrity check PASSED")

    # Save dataset
    output_path = out_dir / "delta_pairs_nmc.parquet"
    delta_df.to_parquet(output_path, index=False)
    print(f"  [delta_features] Saved to {output_path}")

    # Save provenance sidecar
    provenance = {
        "module": "member2_modeling/delta/delta_features",
        "description": "NMC one-step-ahead delta SOH pairs with lag features",
        "rows_per_split": rows_per_split,
        "total_rows": int(len(delta_df)),
        "feature_cols": PADM_FEATURE_COLS,
        "lag_imputation_means": impute_means,
        "soh_clip_range": [SOH_CLIP_MIN, SOH_CLIP_MAX],
        "lag_depth": LAG_DEPTH,
        "split_ratios": {
            "train": TRAIN_FRAC,
            "val": VAL_FRAC,
            "test": TEST_FRAC,
        },
        "notes": [
            "delta_target = SOH(i+1) - SOH(i); positive values are valid.",
            "Lag features built from ground-truth SOH only (no model predictions).",
            "Lag NaNs at cell boundaries imputed with training-set mean.",
            "Feature integrity verified: no forbidden columns in feature set.",
        ],
    }
    prov_path = out_dir / "delta_features_provenance.json"
    prov_path.write_text(json.dumps(provenance, indent=2), encoding="utf-8")

    return {
        "rows_per_split": rows_per_split,
        "impute_means": impute_means,
        "output_path": str(output_path),
        "feature_cols": PADM_FEATURE_COLS,
        "integrity_passed": True,
    }


